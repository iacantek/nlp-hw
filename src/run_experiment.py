def load_checkpoint(
    checkpoint_path: Path,
    expected_backend: str | None = None,
) -> dict[str, dict[str, Any]]:
    """Load completed run records from a JSONL checkpoint file.

    If `expected_backend` is specified, only records generated by that backend
    are retained (preventing `--backend hf --resume` from reusing simulated runs).
    """
    completed: dict[str, dict[str, Any]] = {}
    if not checkpoint_path.exists():
        return completed
    with open(checkpoint_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            if expected_backend is not None and rec.get("backend") != expected_backend:
                continue
            completed[str(rec["run_id"])] = rec
    return completed


def append_checkpoint(checkpoint_path: Path, record: dict[str, Any]) -> None:
    """Append a single scored run record to the JSONL checkpoint file."""
    checkpoint_path.parent.mkdir(parents=True, exist_ok=True)
    with open(checkpoint_path, "a", encoding="utf-8") as f:
        f.write(json.dumps(record, ensure_ascii=False) + "\n")


def sample_qualitative_examples(
    scored_runs: list[dict[str, Any]],
    seed: int = 42,
    k: int = 6,
) -> list[dict[str, Any]]:
    """Randomly sample counterbalanced pairs (including failures/flips) for qualitative analysis."""
    rng = random.Random(seed)
    by_key: dict[tuple[int, str, str], dict[str, dict[str, Any]]] = {}
    for r in scored_runs:
        if r.get("condition") != "cross_lingual":
            continue
        key = (int(r["item_id"]), str(r["query_lang"]), str(r["doc_order"]))
        by_key.setdefault(key, {})[str(r["pair_type"])] = r

    paired_records: list[dict[str, Any]] = []
    for (item_id, q_lang, doc_order), pmap in sorted(by_key.items()):
        r1 = pmap.get("pair1_enA_koB")
        r2 = pmap.get("pair2_koA_enB")
        if r1 is None or r2 is None:
            continue
        c1 = r1.get("combined_choice")
        c2 = r2.get("combined_choice")
        regime = f"{c1}->{c2}"
        paired_records.append(
            {
                "item_id": item_id,
                "category": r1["category"],
                "query_lang": q_lang,
                "doc_order": doc_order,
                "query_text": r1["query_text"],
                "claim_a_en": r1["claim_a_en"],
                "claim_a_ko": r1["claim_a_ko"],
                "claim_b_en": r1["claim_b_en"],
                "claim_b_ko": r1["claim_b_ko"],
                "pair1_doc1": r1["doc1_text"],
                "pair1_doc2": r1["doc2_text"],
                "pair1_generated": r1["generated_text"],
                "pair1_choice": c1,
                "pair1_margin": r1["logprob_margin_a_minus_b"],
                "pair2_doc1": r2["doc1_text"],
                "pair2_doc2": r2["doc2_text"],
                "pair2_generated": r2["generated_text"],
                "pair2_choice": c2,
                "pair2_margin": r2["logprob_margin_a_minus_b"],
                "regime": regime,
            }
        )

    if len(paired_records) <= k:
        return paired_records
    return rng.sample(paired_records, k)


def run_for_model(
    model_name: str,
    prompts: list[PromptInstance],
    backend_type: str = "simulate",
    quantization: str = "4bit",
    max_new_tokens: int = 24,
    seed: int = 42,
    output_dir: Path = Path("results"),
    resume: bool = True,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Run all prompts for a single model and return (scored_runs, analysis_summary)."""
    model_id = resolve_model_id(model_name)
    safe_name = model_id.replace("/", "__")
    checkpoint_path = output_dir / f"runs_{safe_name}.jsonl"

    completed = (
        load_checkpoint(checkpoint_path, expected_backend=backend_type)
        if resume
        else {}
    )
    if checkpoint_path.exists() and (not resume or len(completed) == 0):
        checkpoint_path.unlink()

    if backend_type == "simulate":
        backend: Any = SimulatedModelBackend(model_name=model_id, seed=seed)
    elif backend_type == "hf":
        backend = HuggingFaceModelBackend(
            model_name=model_id,
            quantization=quantization,
            max_new_tokens=max_new_tokens,
        )
    else:
        raise ValueError(f"Unknown backend_type: {backend_type!r}")

    scored_runs: list[dict[str, Any]] = []
    t0 = time.time()
    n_total = len(prompts)

    for idx, prompt in enumerate(prompts, start=1):
        if prompt.run_id in completed:
            scored_runs.append(completed[prompt.run_id])
            continue

        rec = backend.evaluate_prompt(prompt)
        rec["backend"] = backend_type
        scored_runs.append(rec)
        append_checkpoint(checkpoint_path, rec)

        if idx % 100 == 0 or idx == n_total:
            elapsed = time.time() - t0
            print(
                f"[{model_id}] Completed {idx}/{n_total} runs ({elapsed:.1f}s elapsed)"
            )

    analysis = analyze_model_runs(scored_runs, model_name=model_id)
    analysis["sampled_examples"] = sample_qualitative_examples(
        scored_runs, seed=seed, k=8
    )
    return scored_runs, analysis


def print_concise_report(summary: dict[str, Any]) -> None:
    """Print a formatted summary table of the primary metrics to stdout."""
    print("\n" + "=" * 78)
    print("CROSS-LINGUAL RAG CONFLICT EVALUATION SUMMARY")
    print("=" * 78)
    for model_id, mdata in summary.get("models", {}).items():
        print(f"\nModel: {model_id}")
        cb = mdata["closed_book"]["by_query_lang"]
        print(
            f"  Closed-Book Exact Acc: EN = {cb['en']['exact_accuracy']*100:.1f}%, "
            f"KO = {cb['ko']['exact_accuracy']*100:.1f}%"
        )
        mono = mdata["monolingual_baseline"]
        print(
            f"  Monolingual Conflict Acc: EN = {mono['en']['factual_accuracy']*100:.1f}%, "
            f"KO = {mono['ko']['factual_accuracy']*100:.1f}%, "
            f"All = {mono['all']['factual_accuracy']*100:.1f}%"
        )
        xling = mdata["cross_lingual_by_query_lang"]
        for q_lang in ("en", "ko", "all"):
            c = xling[q_lang]["combined"]
            reg = c["regime_rates"]
            mc = c["mcnemar"]
            print(
                f"  Cross-Lingual (query={q_lang.upper():3s}): "
                f"EPR = {c['epr']*100:.1f}% "
                f"[95% CI: {c['epr_ci_95'][0]*100:.1f}%, {c['epr_ci_95'][1]*100:.1f}%] | "
                f"A->B (EN flip) = {reg['en_flip_A_to_B']*100:.1f}%, "
                f"B->A (KO flip) = {reg['ko_flip_B_to_A']*100:.1f}%, "
                f"A->A (Truth) = {reg['truth_consistent_A_to_A']*100:.1f}% | "
                f"McNemar chi2 = {mc['chi2_cc']:.1f} (p = {mc['p_value_exact']:.4g})"
            )
    print("=" * 78 + "\n")


def run_experiment_pipeline(
    models: list[str],
    backend: str = "simulate",
    quantization: str = "4bit",
    max_new_tokens: int = 24,
    seed: int = 42,
    limit_per_category: int | None = None,
    include_monolingual_baseline: bool = True,
    output_dir: Path | str = "results",
    resume: bool = False,
    export_latex: bool = False,
) -> dict[str, Any]:
    """Execute the end-to-end experiment across specified models and save summary JSON."""
    random.seed(seed)
    out_dir = Path(output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    examples = load_conflict_dataset(limit_per_category=limit_per_category)
    prompts = build_all_prompts(
        examples, include_monolingual_baseline=include_monolingual_baseline
    )

    summary: dict[str, Any] = {
        "metadata": {
            "seed": seed,
            "backend": backend,
            "quantization": quantization,
            "n_items": len(examples),
            "n_prompts_per_model": len(prompts),
            "include_monolingual_baseline": include_monolingual_baseline,
        },
        "models": {},
    }

    for model_name in models:
        model_id = resolve_model_id(model_name)
        _, analysis = run_for_model(
            model_name=model_id,
            prompts=prompts,
            backend_type=backend,
            quantization=quantization,
            max_new_tokens=max_new_tokens,
            seed=seed,
            output_dir=out_dir,
            resume=resume,
        )
        summary["models"][model_id] = analysis

    results_json_path = out_dir / "experiment_results.json"
    with open(results_json_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    print_concise_report(summary)

    if export_latex:
        macro_path = export_macros_to_file(results_json_path, DEFAULT_MACROS_PATH)
        print(f"Updated LaTeX macros at {macro_path}")

    return summary


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run Cross-Lingual RAG Conflict Experiments."
    )
    parser.add_argument(
        "--models",
        nargs="+",
        default=["qwen", "llama"],
        help="Models to evaluate (e.g. 'qwen', 'llama', or full HF repo IDs)",
    )
    parser.add_argument(
        "--backend",
        choices=["simulate", "hf"],
        default="simulate",
        help="Inference backend: 'hf' for Google Colab GPU, 'simulate' for local dry-run",
    )
    parser.add_argument(
        "--quantization",
        choices=["4bit", "8bit", "fp16"],
        default="4bit",
        help="Quantization mode for HuggingFace backend on Colab T4 GPU",
    )
    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=24,
        help="Maximum new tokens to generate per prompt",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for reproducibility",
    )
    parser.add_argument(
        "--limit-per-category",
        type=int,
        default=None,
        help="Optional cap on items per category (default: all 50 per category = 150)",
    )
    parser.add_argument(
        "--output-dir",
        type=str,
        default="results",
        help="Directory to write JSONL checkpoints and experiment_results.json",
    )
    parser.add_argument(
        "--resume",
        action="store_true",
        help="Resume from existing JSONL checkpoints in output-dir",
    )
    parser.add_argument(
        "--export-latex",
        action="store_true",
        help="Export results into docs/tex/tex/00_results_macros.tex",
    )
    args = parser.parse_args()

    run_experiment_pipeline(
        models=args.models,
        backend=args.backend,
        quantization=args.quantization,
        max_new_tokens=args.max_new_tokens,
        seed=args.seed,
        limit_per_category=args.limit_per_category,
        output_dir=args.output_dir,
        resume=args.resume,
        export_latex=args.export_latex,
    )


if __name__ == "__main__":
    main()
