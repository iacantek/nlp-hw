"""Main experiment runner for Cross-Lingual Factual Conflict Evaluation in mRAG.

Compatible with Google Colab (single NVIDIA T4 GPU) and local CPU execution.
Supports incremental JSONL checkpointing so interrupted Colab sessions can resume
without repeating completed inference calls.

Usage on Google Colab (Full GPU Inference):
    python -m src.run_experiment --backend hf --models qwen llama --quantization 4bit

Usage for Fast Local Verification / Simulation:
    python -m src.run_experiment --backend simulate --models qwen llama --export-latex
"""

