"""Export experimental results into LaTeX macros for the ACL manuscript.

Reads a `results_summary.json` produced by `src.run_experiment` and generates
`docs/tex/tex/00_results_macros.tex`, allowing all tables and inline numbers in
the paper to be updated automatically and deterministically.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

DEFAULT_MACROS_PATH = (
    Path(__file__).resolve().parent.parent / "docs" / "tex" / "tex" / "00_results_macros.tex"
)


def _fmt_pct(val: float, decimals: int = 1) -> str:
    return f"{val * 100.0:.{decimals}f}"


def _fmt_num(val: float, decimals: int = 2) -> str:
    return f"{val:.{decimals}f}"


def _fmt_pval(p: float) -> str:
    if p < 0.0001:
        return "<0.0001"
    if p < 0.001:
        return "<0.001"
    return f"{p:.3f}"


def generate_latex_macros(summary: dict[str, Any]) -> str:
    """Convert `summary` dictionary from `run_experiment` into LaTeX `\\newcommand` definitions."""
    models = summary.get("models", {})
    qwen = models.get("Qwen/Qwen2.5-7B-Instruct", {})
    llama = models.get("meta-llama/Llama-3.1-8B-Instruct", {})

    lines: list[str] = [
        "% Auto-generated by src/export_tex.py — DO NOT EDIT MANUALLY",
        "% Update by running: python -m src.export_tex --results results/experiment_results.json",
        "",
    ]

    def add_macro(name: str, value: str) -> None:
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    for prefix, mdata in [("qwen", qwen), ("llama", llama)]:
        if not mdata:
            continue

        # 1. Closed-book baseline
        cb = mdata.get("closed_book", {})
        cb_lang = cb.get("by_query_lang", {})
        cb_en = cb_lang.get("en", {})
        cb_ko = cb_lang.get("ko", {})
        strata = cb.get("strata_counts", {})

        add_macro(f"{prefix}CBAccEN", _fmt_pct(cb_en.get("exact_accuracy", 0.0)))
        add_macro(f"{prefix}CBAccKO", _fmt_pct(cb_ko.get("exact_accuracy", 0.0)))
        add_macro(f"{prefix}CBLcEN", _fmt_pct(cb_en.get("language_consistency_rate", 0.0)))
        add_macro(f"{prefix}CBLcKO", _fmt_pct(cb_ko.get("language_consistency_rate", 0.0)))
        add_macro(f"{prefix}KnownBothN", str(strata.get("known_both", 0)))
        add_macro(f"{prefix}KnownENOnlyN", str(strata.get("known_en_only", 0)))
        add_macro(f"{prefix}KnownKOOnlyN", str(strata.get("known_ko_only", 0)))
        add_macro(f"{prefix}UnknownBothN", str(strata.get("unknown_both", 0)))

        # 2. Monolingual conflict baseline
        mono = mdata.get("monolingual_baseline", {})
        for l_key, l_tag in [("en", "EN"), ("ko", "KO"), ("all", "All")]:
            ml = mono.get(l_key, {})
            add_macro(f"{prefix}MonoAcc{l_tag}", _fmt_pct(ml.get("factual_accuracy", 0.0)))
            add_macro(
                f"{prefix}MonoOverride{l_tag}",
                _fmt_pct(ml.get("false_override_rate", 0.0)),
            )
            add_macro(
                f"{prefix}MonoFirstDoc{l_tag}",
                _fmt_pct(ml.get("first_doc_preference_rate", 0.0)),
            )
            add_macro(
                f"{prefix}MonoAbstain{l_tag}",
                _fmt_pct(ml.get("abstention_rate", 0.0)),
            )
            add_macro(
                f"{prefix}MonoLC{l_tag}",
                _fmt_pct(ml.get("language_consistency_rate", 0.0)),
            )

        # 3. Cross-lingual conflict by query language
        xling = mdata.get("cross_lingual_by_query_lang", {})
        for l_key, l_tag in [("en", "EN"), ("ko", "KO"), ("all", "All")]:
            comb = xling.get(l_key, {}).get("combined", {})
            lp_only = xling.get(l_key, {}).get("logprob", {})
            txt_only = xling.get(l_key, {}).get("text_only", {})
            reg = comb.get("regime_rates", {})
            reg_n = comb.get("regime_counts", {})
            mc = comb.get("mcnemar", {})
            lps = comb.get("logprob_shift", {})
            ci = comb.get("epr_ci_95", [0.0, 0.0])

            add_macro(f"{prefix}EPR{l_tag}", _fmt_pct(comb.get("epr", 0.0)))
            add_macro(f"{prefix}EPRLP{l_tag}", _fmt_pct(lp_only.get("epr", 0.0)))
            add_macro(f"{prefix}EPRTxt{l_tag}", _fmt_pct(txt_only.get("epr", 0.0)))
            add_macro(f"{prefix}EPRCILow{l_tag}", _fmt_pct(ci[0]))
            add_macro(f"{prefix}EPRCIHigh{l_tag}", _fmt_pct(ci[1]))
            add_macro(
                f"{prefix}FlipABRate{l_tag}",
                _fmt_pct(reg.get("en_flip_A_to_B", 0.0)),
            )
            add_macro(
                f"{prefix}FlipBARate{l_tag}",
                _fmt_pct(reg.get("ko_flip_B_to_A", 0.0)),
            )
            add_macro(
                f"{prefix}TruthAARate{l_tag}",
                _fmt_pct(reg.get("truth_consistent_A_to_A", 0.0)),
            )
            add_macro(
                f"{prefix}FalseBBRate{l_tag}",
                _fmt_pct(reg.get("false_consistent_B_to_B", 0.0)),
            )
            add_macro(f"{prefix}FlipABN{l_tag}", str(reg_n.get("en_flip_A_to_B", 0)))
            add_macro(f"{prefix}FlipBAN{l_tag}", str(reg_n.get("ko_flip_B_to_A", 0)))
            add_macro(
                f"{prefix}TruthAAN{l_tag}",
                str(reg_n.get("truth_consistent_A_to_A", 0)),
            )
            add_macro(
                f"{prefix}FalseBBN{l_tag}",
                str(reg_n.get("false_consistent_B_to_B", 0)),
            )
            add_macro(
                f"{prefix}CondENFlip{l_tag}",
                _fmt_pct(mc.get("conditional_en_flip_rate", 0.5)),
            )
            add_macro(f"{prefix}McNemarChi{l_tag}", _fmt_num(mc.get("chi2_cc", 0.0), 1))
            add_macro(
                f"{prefix}McNemarP{l_tag}", _fmt_pval(mc.get("p_value_exact", 1.0))
            )
            add_macro(
                f"{prefix}FactAcc{l_tag}",
                _fmt_pct(comb.get("factual_accuracy", 0.0)),
            )
            add_macro(
                f"{prefix}PairOneAcc{l_tag}",
                _fmt_pct(comb.get("pair1_en_truth_accuracy", 0.0)),
            )
            add_macro(
                f"{prefix}PairTwoOverride{l_tag}",
                _fmt_pct(comb.get("pair2_en_false_override_rate", 0.0)),
            )
            add_macro(
                f"{prefix}FirstDoc{l_tag}",
                _fmt_pct(comb.get("first_doc_preference_rate", 0.0)),
            )
            add_macro(
                f"{prefix}Abstain{l_tag}",
                _fmt_pct(comb.get("abstention_rate", 0.0)),
            )
            add_macro(
                f"{prefix}LC{l_tag}",
                _fmt_pct(comb.get("language_consistency_rate", 0.0)),
            )
            add_macro(
                f"{prefix}LPShiftMean{l_tag}",
                _fmt_num(lps.get("mean", 0.0), 2),
            )
            add_macro(
                f"{prefix}LPShiftT{l_tag}",
                _fmt_num(lps.get("t_stat", 0.0), 1),
            )

        # 4. Ablation by prior knowledge
        pk = mdata.get("ablation_by_prior_knowledge", {})
        for s_key, s_tag in [
            ("known_both", "KnownBoth"),
            ("known_en_only", "KnownENOnly"),
            ("unknown_both", "UnknownBoth"),
            ("any_known", "AnyKnown"),
        ]:
            s_all = pk.get(s_key, {}).get("all", {})
            s_en = pk.get(s_key, {}).get("en", {})
            s_ko = pk.get(s_key, {}).get("ko", {})
            add_macro(f"{prefix}PK{s_tag}EPRAll", _fmt_pct(s_all.get("epr", 0.0)))
            add_macro(f"{prefix}PK{s_tag}EPREN", _fmt_pct(s_en.get("epr", 0.0)))
            add_macro(f"{prefix}PK{s_tag}EPRKO", _fmt_pct(s_ko.get("epr", 0.0)))
            add_macro(
                f"{prefix}PK{s_tag}OverrideAll",
                _fmt_pct(s_all.get("pair2_en_false_override_rate", 0.0)),
            )
            add_macro(
                f"{prefix}PK{s_tag}FactAccAll",
                _fmt_pct(s_all.get("factual_accuracy", 0.0)),
            )

        # 5. Ablation by category (entity, date, number)
        cat_map = mdata.get("ablation_by_category", {})
        for c_key, c_tag in [
            ("entity", "Entity"),
            ("date", "Date"),
            ("number", "Number"),
        ]:
            c_all = cat_map.get(c_key, {}).get("all", {})
            c_en = cat_map.get(c_key, {}).get("en", {})
            c_ko = cat_map.get(c_key, {}).get("ko", {})
            add_macro(f"{prefix}Cat{c_tag}EPRAll", _fmt_pct(c_all.get("epr", 0.0)))
            add_macro(f"{prefix}Cat{c_tag}EPREN", _fmt_pct(c_en.get("epr", 0.0)))
            add_macro(f"{prefix}Cat{c_tag}EPRKO", _fmt_pct(c_ko.get("epr", 0.0)))
            add_macro(
                f"{prefix}Cat{c_tag}LCKO",
                _fmt_pct(c_ko.get("language_consistency_rate", 0.0)),
            )
            add_macro(
                f"{prefix}Cat{c_tag}FlipABAll",
                _fmt_pct(c_all.get("regime_rates", {}).get("en_flip_A_to_B", 0.0)),
            )

        # 6. Ablation by document order (en_first vs ko_first)
        ord_map = mdata.get("ablation_by_doc_order", {})
        for o_key, o_tag in [("en_first", "ENFirst"), ("ko_first", "KOFirst")]:
            o_all = ord_map.get(o_key, {}).get("all", {})
            o_en = ord_map.get(o_key, {}).get("en", {})
            o_ko = ord_map.get(o_key, {}).get("ko", {})
            add_macro(f"{prefix}Ord{o_tag}EPRAll", _fmt_pct(o_all.get("epr", 0.0)))
            add_macro(f"{prefix}Ord{o_tag}EPREN", _fmt_pct(o_en.get("epr", 0.0)))
            add_macro(f"{prefix}Ord{o_tag}EPRKO", _fmt_pct(o_ko.get("epr", 0.0)))

    lines.append("")
    return "\n".join(lines)


def export_macros_to_file(
    results_path: Path | str,
    output_tex_path: Path | str = DEFAULT_MACROS_PATH,
) -> Path:
    """Read `results_path` JSON and write LaTeX macros to `output_tex_path`."""
    with open(results_path, "r", encoding="utf-8") as f:
        summary = json.load(f)

    tex_content = generate_latex_macros(summary)
    out_path = Path(output_tex_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(tex_content)
    return out_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export experiment_results.json into LaTeX macros."
    )
    parser.add_argument(
        "--results",
        type=str,
        default="results/experiment_results.json",
        help="Path to experiment_results.json",
    )
    parser.add_argument(
        "--output",
        type=str,
        default=str(DEFAULT_MACROS_PATH),
        help="Output path for LaTeX macros file",
    )
    args = parser.parse_args()
    out = export_macros_to_file(args.results, args.output)
    print(f"Exported LaTeX macros to {out}")


if __name__ == "__main__":
    main()
