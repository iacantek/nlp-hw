def build_dataset_records() -> list[dict[str, Any]]:
    """Construct the full list of 150 structured conflict records."""
    records: list[dict[str, Any]] = []
    seen_ids: set[int] = set()

    for idx, item in enumerate(RAW_MKQA_ITEMS):
        (
            mkqa_id,
            category,
            query_en,
            query_ko,
            claim_a_en,
            claim_a_ko,
            claim_b_en,
            claim_b_ko,
            template_en,
            template_ko,
        ) = item

        if mkqa_id in seen_ids:
            raise ValueError(f"Duplicate mkqa_example_id detected: {mkqa_id}")
        seen_ids.add(mkqa_id)

        if claim_a_en.strip().lower() == claim_b_en.strip().lower():
            raise ValueError(f"Item {idx} has identical EN claims: {claim_a_en}")
        if claim_a_ko.strip() == claim_b_ko.strip():
            raise ValueError(f"Item {idx} has identical KO claims: {claim_a_ko}")
        if "{entity}" not in template_en or "{entity}" not in template_ko:
            raise ValueError(f"Item {idx} missing {{entity}} placeholder in template")

        passage_en_a = template_en.replace("{entity}", claim_a_en)
        passage_en_b = template_en.replace("{entity}", claim_b_en)
        passage_ko_a = resolve_korean_particles(template_ko.replace("{entity}", claim_a_ko))
        passage_ko_b = resolve_korean_particles(template_ko.replace("{entity}", claim_b_ko))

        records.append(
            {
                "id": idx,
                "mkqa_example_id": mkqa_id,
                "category": category,
                "query_en": query_en,
                "query_ko": query_ko,
                "claim_a_en": claim_a_en,
                "claim_a_ko": claim_a_ko,
                "claim_b_en": claim_b_en,
                "claim_b_ko": claim_b_ko,
                "template_en": template_en,
                "template_ko": template_ko,
                "passage_en_a": passage_en_a,
                "passage_en_b": passage_en_b,
                "passage_ko_a": passage_ko_a,
                "passage_ko_b": passage_ko_b,
            }
        )

    return records


def save_dataset(output_path: Path = DEFAULT_DATASET_PATH) -> Path:
    """Build and write the 150-item dataset to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    records = build_dataset_records()
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)
    return output_path


if __name__ == "__main__":
    path = save_dataset()
    print(f"Saved {len(RAW_MKQA_ITEMS)} items to {path}")
